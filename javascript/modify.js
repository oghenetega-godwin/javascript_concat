// Using the replace() method to replace a word
const statement = "I would become a business mogul in the future";
console.log(statement);

const newStatement = statement.replace("mogul", "tycoon");
console.log(newStatement);

// Using the repeat() method to repeat at a specific number of time

const loop = "I will be a The President of the Federal Republic of Nigeria";
console.log(loop);

const looped_statement = loop.repeat(4);
console.log(looped_statement);